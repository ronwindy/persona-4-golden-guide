// Writes src/styles/header-icons.css: one CSS mask per Lucide icon named in src/lib/header-icon-rules.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { HEADER_ICON_NAMES } from '../../src/lib/header-icon-rules.mjs';

const ICON_DIR = path.resolve('node_modules/@lucide/astro/src/icons');

const svgOf = (name) => {
  const file = path.join(ICON_DIR, `${name}.ts`);
  if (!fs.existsSync(file)) throw new Error(`Unknown Lucide icon "${name}" in header-icon-rules.mjs`);
  const data = JSON.parse(/const iconData: LucideIconData = (\{.*\});/.exec(fs.readFileSync(file, 'utf8'))[1]);
  const body = data.node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}='${v}'`).join(' ')}/>`).join('');
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2.5' stroke-linecap='round' stroke-linejoin='round'>${body}</svg>`;
};

export function writeHeaderIconsCss(outFile = 'src/styles/header-icons.css') {
  const rules = HEADER_ICON_NAMES.sort().map((n) => `.guide-body [data-icon="${n}"] { --header-icon: url("data:image/svg+xml,${encodeURIComponent(svgOf(n)).replace(/'/g, '%27')}"); }`);
  fs.writeFileSync(outFile, `/* Generated by scripts/lib/header-icons-css.mjs (run by npm run extract). Do not edit. */\n${rules.join('\n')}\n`);
  return HEADER_ICON_NAMES.length;
}
